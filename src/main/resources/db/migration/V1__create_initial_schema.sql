CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE IF NOT EXISTS show (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    price INTEGER NOT NULL,
    user_limit INTEGER DEFAULT 4 NOT NULL,
    CONSTRAINT pk_show PRIMARY KEY (id),
    CONSTRAINT ck_show_price CHECK (price >= 0),
    CONSTRAINT ck_show_user_limit CHECK (user_limit > 0)
);

CREATE TABLE IF NOT EXISTS seat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    state VARCHAR(255) DEFAULT 'AVAILABLE' NOT NULL,
    seat_number VARCHAR(255) NOT NULL,
    user_id BIGINT,
    show_id BIGINT NOT NULL,
    CONSTRAINT pk_seat PRIMARY KEY (id),
    CONSTRAINT uk_seat_show_number UNIQUE (show_id, seat_number),
    CONSTRAINT ck_seat_state CHECK (state IN ('AVAILABLE', 'HELD', 'CONFIRMED')),
    CONSTRAINT fk_seat_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_seat_show FOREIGN KEY (show_id) REFERENCES show (id)
);

CREATE TABLE IF NOT EXISTS reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    show_id BIGINT NOT NULL,
    amount_paise BIGINT NOT NULL,
    idempotency_key VARCHAR(255) NOT NULL,
    status VARCHAR(255) DEFAULT 'CONFIRMED' NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    cancelled_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_reservations PRIMARY KEY (id),
    CONSTRAINT uk_reservation_user_idempotency UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_reservation_amount CHECK (amount_paise >= 0),
    CONSTRAINT ck_reservation_status CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    CONSTRAINT fk_reservation_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_reservation_show FOREIGN KEY (show_id) REFERENCES show (id)
);

CREATE TABLE IF NOT EXISTS reservation_seats (
    reservation_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL,
    CONSTRAINT uk_reservation_seat UNIQUE (reservation_id, seat_id),
    CONSTRAINT fk_reservation_seats_reservation
        FOREIGN KEY (reservation_id) REFERENCES reservations (id),
    CONSTRAINT fk_reservation_seats_seat
        FOREIGN KEY (seat_id) REFERENCES seat (id)
);

CREATE INDEX IF NOT EXISTS idx_seat_user ON seat (user_id);
CREATE INDEX IF NOT EXISTS idx_seat_state ON seat (state);
CREATE INDEX IF NOT EXISTS idx_reservation_user_show_status
    ON reservations (user_id, show_id, status);
CREATE INDEX IF NOT EXISTS idx_reservation_show ON reservations (show_id);
CREATE INDEX IF NOT EXISTS idx_reservation_seats_seat ON reservation_seats (seat_id);
